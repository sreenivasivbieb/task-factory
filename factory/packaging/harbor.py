"""Export a task package in Harbor's task format (github.com/laude-institute/harbor).

Harbor (Apache-2.0, from the Terminal-Bench team) runs many agents (Claude Code,
Codex CLI, OpenHands, ...) on tasks laid out like this::

    <task>/
      instruction.md
      task.toml                 Harbor schema (metadata, verifier, agent, environment)
      environment/Dockerfile    + repo.tar: the pinned repo, so the folder is self-contained
      solution/solve.sh         applies solution.diff (used by Harbor's oracle agent)
      tests/test.sh             verifier: restores tests, copies hidden tests, runs them,
                                writes the reward to /logs/verifier/reward.txt
      tests/fail_to_pass.json   SWE-bench style: the feature tests (fail before, pass after)
      tests/pass_to_pass.json   SWE-bench style: the existing tests that must keep passing

Reward (the hackathon's validation matrix): 0.0 if any existing (pass-to-pass) test fails;
otherwise the share of feature tests that pass (1.0 when all do). The nop agent gets 0.0, the
oracle 1.0. The verifier runs without network access.

Inside the container Harbor mounts ``solution/`` at ``/solution`` and
``tests/`` at ``/tests``. The repo lives at ``/repo``.
"""

from __future__ import annotations

import json
import posixpath
import re
import shlex
import subprocess
import shutil
import tempfile
from pathlib import Path

from ..models import EnvConfig
from ..runner.test_runner import build_command
from ..sandbox.base import git_archive, render_dockerfile
from . import toml_writer
from .verify import package_repo, read_package
from ..harness.protect import restore_sh
from ..repo.loader import export_clean

REWARD = "/logs/verifier/reward.txt"


def _title(instruction: str, fallback: str) -> str:
    for line in instruction.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return fallback


def _report_glob(env: EnvConfig) -> str:
    path = env.report_path.rstrip("/")
    is_dir = env.report_path.endswith("/") or "." not in path.rsplit("/", 1)[-1]
    return f"{shlex.quote(path)}/*.xml" if is_dir else shlex.quote(path)


def verifier_script(env: EnvConfig, known_failures: list[str], test_files: list[str] | None = None,
                    n_feature: int = 0, fail_to_pass: list[str] | None = None) -> str:
    """Bash verifier with the validation-matrix reward.

    1. undo the agent's changes to protected (test and test-config) files, copy the hidden tests in;
    2. regression: run the suite without the feature tests (and without tests that already failed
       at the starting commit); any failure gives reward 0;
    3. feature: run the hidden feature tests; the reward is the share that ran and passed.

    Exit codes alone are not enough: a solver could stop the hidden tests from being collected,
    so for JUnit reports the verifier counts the feature test cases that ran and passed.
    Without a JUnit report the feature part is all or nothing (exit code).
    """
    fail_to_pass = list(fail_to_pass or [])
    n_feature = n_feature or len(fail_to_pass)
    regression = build_command(env, None)
    skip = sorted(set(known_failures) | (set(fail_to_pass) if env.deselect else set()))
    if env.deselect and skip:
        regression += " " + " ".join(env.deselect.replace("{id}", shlex.quote(t)) for t in skip)
    if env.select == "ids" and fail_to_pass:
        feature = build_command(env, fail_to_pass)
    else:
        feature = build_command(env, test_files) if test_files else None
    report = _report_glob(env)
    clear_report = f"rm -rf {shlex.quote(env.report_path.rstrip('/'))}"
    lines = [
        "#!/bin/bash",
        "# Verifier generated by task-factory.",
        "# Reward: 0 if any existing test fails; otherwise passed feature tests / all feature tests.",
        "set -uo pipefail",
        "mkdir -p /logs/verifier",
        f"reward() {{ echo \"$1\" > {REWARD}; echo \"[verifier] reward $1${{2:+ ($2)}}\"; exit 0; }}",
        f"cd {env.workdir} || reward 0 'no repo'",
        f"git config --global --add safe.directory {env.workdir} 2>/dev/null || true",
        "mkdir -p .factory",
        f"TAMPERED=$({restore_sh(env.protected_paths)})",
        '[ -n "$TAMPERED" ] && echo "[verifier] undid agent changes to protected files: $TAMPERED"',
        "cp -R /tests/files/. ./",
    ]
    for i, path in enumerate(sorted(env.helper_files)):  # files the test command needs (see ecosystems.toml)
        lines.append(f"mkdir -p {shlex.quote(posixpath.dirname(path) or '.')} && cp /tests/helpers/{i} {shlex.quote(path)}")
    if not env.deselect and fail_to_pass:
        lines.append("# this test runner cannot skip single tests: the regression run includes the feature tests")
    lines += [
        "echo '[verifier] regression run (existing tests)'",
        clear_report,
        regression,
        '[ "$?" -eq 0 ] || reward 0 "an existing test failed"',
    ]
    if feature is None:
        lines.append("reward 1 'no feature tests'")
    else:
        lines += [
            "echo '[verifier] feature run (hidden tests)'",
            clear_report,
            feature,
            "rc=$?",
        ]
        if env.report_format == "junit" and n_feature:
            lines += [
                f"ran=$(cat {report} 2>/dev/null | grep -o '<testcase[ >]' | wc -l)",
                f"bad=$(cat {report} 2>/dev/null | grep -cE '<(failure|error|skipped)[ >/]' || true)",
                "passed=$((ran - bad))",
                f"[ \"$passed\" -gt {n_feature} ] && passed={n_feature}",
                '[ "$passed" -lt 0 ] && passed=0',
                f'[ "$passed" -eq 0 ] && reward 0 "0 of {n_feature} feature tests passed"',
                f'[ "$rc" -eq 0 ] && [ "$passed" -eq {n_feature} ] && reward 1 "all {n_feature} feature tests passed"',
                f"reward \"$(awk -v p=\"$passed\" 'BEGIN {{ printf \"%.4f\", p / {n_feature} }}')\" "
                f"\"$passed of {n_feature} feature tests passed\"",
            ]
        else:
            lines.append('[ "$rc" -eq 0 ] && reward 1 "feature tests passed" || reward 0 "feature tests failed"')
    lines.append("")
    return "\n".join(lines)


def solve_script(env: EnvConfig) -> str:
    return "\n".join([
        "#!/bin/bash",
        "# Oracle solution: apply the reference patch.",
        "set -euo pipefail",
        f"cd {env.workdir}",
        f"git config --global --add safe.directory {env.workdir} 2>/dev/null || true",
        "git apply --whitespace=nowarn /solution/solution.diff",
        "",
    ])


_LICENSES = [  # (SPDX id, phrases that identify the license text)
    ("Apache-2.0", ["apache license", "version 2.0"]),
    ("BSD-3-Clause", ["redistribution and use in source and binary forms", "neither the name"]),
    ("BSD-2-Clause", ["redistribution and use in source and binary forms"]),
    ("MIT", ["permission is hereby granted, free of charge"]),
    ("GPL-3.0", ["gnu general public license", "version 3"]),
    ("GPL-2.0", ["gnu general public license", "version 2"]),
    ("MPL-2.0", ["mozilla public license", "2.0"]),
]


def detect_license(repo: Path) -> tuple[str, str | None]:
    """(SPDX id or "unknown", license file name) from the license file(s) in the repo root."""
    files = sorted(p for p in Path(repo).iterdir()
                   if p.is_file() and re.match(r"(?i)(licen[cs]e|copying)", p.name))
    found = []
    for f in files:
        text = " ".join(f.read_text(encoding="utf-8", errors="replace").lower().split())
        for spdx, phrases in _LICENSES:
            if all(ph in text for ph in phrases):
                found.append(spdx)
                break
        if "public domain" in text and "Public-Domain" not in found:
            found.append("Public-Domain")
    name = files[0].name if files else None
    return (" OR ".join(dict.fromkeys(found)) or "unknown"), name


def repository_url(source: str) -> str:
    """The public URL of the repository: the source itself, or a local clone's ``origin`` remote."""
    if re.match(r"^(https?|git|ssh)://|^git@", source):
        return source
    try:
        r = subprocess.run(["git", "-C", source, "remote", "get-url", "origin"],
                           capture_output=True, text=True, timeout=10)
    except (OSError, subprocess.SubprocessError):
        return source
    url = r.stdout.strip()
    return url if r.returncode == 0 and url else source


def harbor_task_toml(meta, title: str, env: EnvConfig, license_id: str = "unknown",
                     license_file: str | None = None) -> str:
    data = {
        "schema_version": "1.4",
        "base_commit": meta.commit_sha,
        "metadata": {
            "task_id": meta.task_id,
            "display_title": title,
            "category": meta.kind,
            "tags": meta.tags,
            "language": meta.language or "",
            "repository": meta.repo_name,
            "repository_url": repository_url(meta.repo),
            "base_commit": meta.commit_sha,
            "base_commit_hash": meta.commit_sha,
            "license": license_id,
            "license_file": license_file or "",
            "generated_by": "task-factory",
            "author": meta.generated_by.author or meta.generated_by.model,
            "model": meta.generated_by.model,
            "test_framework": env.framework,
            "fail_to_pass": meta.fail_to_pass,
            "pass_to_pass_count": len(meta.pass_to_pass),
            "manual_edit": meta.manual_edit,
        },
        # The verifier needs no network: tests must not reach external services.
        "verifier": {"timeout_sec": float(max(600, env.test_timeout_s * 3)), "network_mode": "no-network"},
        "agent": {"timeout_sec": 3600.0},
        # The agent's phase needs the network to reach its model API.
        "environment": {"build_timeout_sec": 1800.0, "cpus": 2, "memory_mb": 4096, "network_mode": "public"},
    }
    return toml_writer.dumps(data)


def check_patch_applies(repo_dir: Path, patch: str) -> None:
    """Fail the export when the reference patch does not apply to the task's repository snapshot
    (for example a snapshot taken from a Windows checkout with CRLF line endings): Harbor's oracle
    would score 0 on such a task."""
    from ..errors import PackageError

    def git(*args, **kw):
        return subprocess.run(["git", "-c", "core.autocrlf=false", *args], cwd=repo_dir,
                              capture_output=True, text=True, **kw)
    git("init", "-q")
    git("add", "-A")
    git("-c", "user.name=factory", "-c", "user.email=factory@localhost", "-c", "commit.gpgsign=false",
        "commit", "-q", "--allow-empty", "-m", "base")
    r = git("apply", "--check", "-", input=patch)
    if r.returncode != 0:
        raise PackageError(f"the reference patch does not apply to the repository snapshot: {r.stderr.strip()[:400]}")


def to_harbor(pkg_dir: Path, out_root: Path) -> Path:
    """Write one package as a self-contained Harbor task under ``out_root``."""
    meta, draft = read_package(pkg_dir)
    env = EnvConfig.load(Path(pkg_dir) / "environment" / "env.json")
    dest = Path(out_root) / meta.task_id
    if dest.exists():
        shutil.rmtree(dest)
    (dest / "environment").mkdir(parents=True)
    (dest / "solution").mkdir()
    (dest / "tests" / "files").mkdir(parents=True)
    with tempfile.TemporaryDirectory(prefix="factory-harbor-") as tmp:
        repo = package_repo(pkg_dir, meta, Path(tmp))
        clean = export_clean(repo, Path(tmp) / "snapshot")
        license_id, license_file = detect_license(clean)
        check_patch_applies(clean, draft.solution_patch)
        git_archive(repo, dest / "environment" / "repo.tar")
    dockerfile = render_dockerfile(env) + 'CMD ["/bin/bash"]\n'
    (dest / "environment" / "Dockerfile").write_text(dockerfile, encoding="utf-8")
    (dest / "instruction.md").write_text(draft.requirements_md, encoding="utf-8")
    title = _title(draft.requirements_md, meta.task_id)
    (dest / "task.toml").write_text(harbor_task_toml(meta, title, env, license_id, license_file), encoding="utf-8")
    (dest / "solution" / "solution.diff").write_text(draft.solution_patch, encoding="utf-8")
    (dest / "solution" / "solve.sh").write_text(solve_script(env), encoding="utf-8")
    for rel, content in draft.test_files.items():
        p = dest / "tests" / "files" / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8")
    for i, path in enumerate(sorted(env.helper_files)):
        helper = dest / "tests" / "helpers" / str(i)
        helper.parent.mkdir(parents=True, exist_ok=True)
        helper.write_text(env.helper_files[path], encoding="utf-8")
    (dest / "tests" / "test.sh").write_text(
        verifier_script(env, meta.known_failures, sorted(draft.test_files), len(meta.fail_to_pass),
                        meta.fail_to_pass), encoding="utf-8")
    (dest / "tests" / "fail_to_pass.json").write_text(json.dumps(meta.fail_to_pass, indent=2) + "\n", encoding="utf-8")
    (dest / "tests" / "pass_to_pass.json").write_text(json.dumps(meta.pass_to_pass, indent=2) + "\n", encoding="utf-8")
    for script in (dest / "solution" / "solve.sh", dest / "tests" / "test.sh"):
        script.chmod(0o755)
    return dest
